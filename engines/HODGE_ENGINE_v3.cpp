// =====================================================================
//  HODGE_ENGINE_v3   (Sparse / Tensorial)
//  Integral Hodge Conjecture verifier for even-dimensional Fermat varieties.
//  Method: Degtyarev-Shimada (arXiv:1405.4683), computational criterion (Sec.5).
//
//  Fermat  X_n^m : x_0^m + ... + x_{n+1}^m = 0   (n even, m>2),  d = n/2.
//  Standard linear d-spaces generate the FULL integral Hodge lattice
//   <=> L(X) primitive in H_n(X)  <=> Tors(H_n(X)/L(X))=0
//   <=> dim_C B_K == dim_{F_p} B_K  for every prime p | m,
//  where B_K = Rbar/(rho_J : J),  Rbar = k[t_1..t_{n+1}]/(phi(t_i)),
//        phi = 1+t+...+t^{m-1},   dim_k Rbar = (m-1)^{n+1} =: DIM.
//
//  When m is prime, primitivity == Integral Hodge Conjecture for X.
//
//  ---- v3 engineering over v2 ----
//  (1) TENSORIAL rho_J: a partition splits the n+2 indices into DISJOINT pairs,
//      so rho_J = tensor product of single-pair factors rho(t_j,t_k).
//      Built directly as a sparse vector in O(#nonzeros), NO dense polynomial
//      multiplication (v2's O(DIM^2) wall is gone).
//  (2) SPARSE incremental Gaussian elimination over F_p with pivot map col->row;
//      the ideal span is generated by CLOSURE of the base rho_J under the n+1
//      variable-shift operators (mult by t_v), so we never materialize DIM*parts
//      dense rows. dim B_K = DIM - rank.
//  (3) GUARDS: abort with a clear message if DIM exceeds a RAM budget, or if a
//      phase stalls past a wall-clock limit. Never hang silently.
//
//  AUDIT == METRIC. Exact modular arithmetic. No floating point. Single thread.
//
//  Index convention: variables t_1..t_{n+1} are the n+1 "free" exponents
//  (slots 0..n in arrays). Original index 0 of the partition is the dependent
//  one (t_0 = (t_1...t_{n+1})^{-1}); the pair containing original index 0 is
//  dropped from rho_J exactly as in v2 (validated).
//  A basis monomial = exponent vector a[0..n], 0<=a[i]<=m-2, encoded mixed-radix
//  base B=m-1:  id = sum a[i]*B^i.
// =====================================================================
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>
#include <unordered_map>
#include <algorithm>
#include <cstdint>
#include <string>
